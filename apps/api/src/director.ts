/**
 * Gemini as Kivo's director. Four passes build a scene; a fifth edits one.
 * Each pass returns constrained JSON that is validated before it is used —
 * Gemini never writes code and never talks to Blender.
 */

const WORLD_RULES = `World conventions (always follow them):
- Units: metres, seconds, degrees.
- Axes: Y is up. The ground is the plane y = 0. X and Z are horizontal.
- Heading (rotationY): 0 faces +Z, 90 faces +X, 180 faces -Z, 270 faces -X.
- Keep the action within about 40 m of the origin unless the idea needs more room.`;

export interface GenerationSettings {
  duration: number;
  fps: number;
  aspect: string;
  style: string;
}

// ───────────── 1. Understanding the prompt ─────────────

export function interpretPrompt(env: Env, prompt: string, settings: GenerationSettings) {
  return geminiJson<Interpretation>(env, {
    label: "interpret",
    temperature: 0.6,
    timeoutMs: 30_000,
    jsonSchema: InterpretationJsonSchema,
    parse: InterpretationSchema,
    system: `You are the director of Kivo, a studio that turns a written idea into a short animated 3D video.
Read the user's idea and describe the film you will make from it.

Accept anything that can be staged with 3D models, movement, cameras and light. If the idea is vague, make confident, tasteful creative choices — do not reject for vagueness.
Set accepted to false ONLY when the text is empty or meaningless, or asks for sexual content, real-person likenesses in harmful situations, hateful content, or gratuitous gore. In that case give a short, kind rejectionReason that suggests what to try instead.

The video is ${settings.duration} seconds long, ${settings.aspect}, in a "${settings.style}" look (${styleHint(settings.style)}). Scope the story so it fits that length: one clear action, not a saga.`,
    user: `Idea:\n"""${prompt}"""`,
  });
}

// ───────────── 2. Planning the scene ─────────────

function libraryText(library: LibraryAction[]): string {
  const groups = new Map<string, string[]>();
  for (const a of library) {
    const key = a.sub_category || a.category || "Other";
    groups.set(key, [...(groups.get(key) ?? []), `${a.action_id}:${a.name}`]);
  }
  return [...groups.entries()].map(([k, v]) => `${k}: ${v.join(", ")}`).join("\n");
}

export function planScene(
  env: Env,
  interpretation: Interpretation,
  prompt: string,
  settings: GenerationSettings,
  limits: Pick<PlanLimits, "maxAssetsPerScene" | "maxCustomMotions">,
  library: LibraryAction[],
) {
  return geminiJson<ScenePlan>(env, {
    label: "plan",
    temperature: 0.7,
    jsonSchema: PlanJsonSchema,
    parse: PlanSchema,
    system: `You are the production designer of Kivo. Plan the 3D models and the world for a ${settings.duration}-second animated video.

Every visible thing is a 3D model generated by Meshy from a text prompt, then placed and animated in Blender. Your job is to choose the models.

${WORLD_RULES}

MODELS
- You may list at most ${limits.maxAssetsPerScene} distinct models. A model can be placed many times later (ten trees need one tree model), so list each distinct model once.
- Spend the budget on what the story needs: the hero first, then the ground, then the most recognisable set pieces.
- Each model's prompt must describe ONE standalone object, with concrete shape, materials and colours. Meshy cannot make whole scenes: write "a ruined concrete skyscraper with broken windows", never "an abandoned city". No backgrounds, no floors under objects, no multiple objects, no text.
- Always include exactly one model of kind "terrain": the ground the action happens on. Prompt it as ONE solid, unbroken, perfectly flat square tile seen from above, e.g. "a solid flat square floor tile of dry desert ground, unbroken surface, even thickness, nothing on it". Put surface character in the look (painted cracks, moss stains, road markings), never in the shape — no holes, gaps, chunks or raised pieces. Use sizeAxis "width" and make it wide enough for all movement plus a margin (typically 30–80 m).
- sizeMeters is the real-world size: a person 1.7, a small robot 1.0, a car 4.5 (sizeAxis "longest"), a tree 6, a building 20–60 (sizeAxis "height").

CHARACTERS AND MOTION
- rig "humanoid" is ONLY for characters that stand on two legs with two clearly separate arms (people, humanoid robots, bipedal creatures). Their prompt must end with "full body, standing in an A-pose with arms away from the body and legs apart" so the skeleton fits.
- THE HERO MUST BE A HUMANOID whenever the idea allows it. Skeletal animation (real walking, running, waving) looks far better than sliding a rigid model. If the idea says "a robot", "a creature", "an alien", "a monster", "a toy", "a mascot" or anything else whose body is not specified, you MUST design the hero as a two-legged, two-armed humanoid with rig "humanoid" — for example a small bipedal robot with a round head, two arms and two legs. Do NOT design wheeled, spherical, hovering or legless heroes unless the idea explicitly asks for that body (a car, a drone, a ball, a fish, a four-legged animal).
- Everything else is rig "none": four-legged animals, birds, fish, vehicles, drones, blobs, props. They cannot bend; they are animated as rigid bodies that slide, hop, hover, spin and tilt. Plan the story so that still reads well.
- A humanoid always gets "walk" and "run" clips for free. In actionIds, list up to 4 extra clips it needs from the animation library below (use the numeric ids). Give every humanoid an idle clip (0 is "Idle") if it ever stands still.
${
  limits.maxCustomMotions > 0
    ? `- If the story needs one body motion that no library clip covers, describe it in customMotionPrompt (for at most ${limits.maxCustomMotions} character${limits.maxCustomMotions === 1 ? "" : "s"}), with customMotionSeconds between 2 and 10. Otherwise leave it empty and 0.`
    : "- Leave customMotionPrompt empty and customMotionSeconds 0."
}

WORLD
- skyTop / skyHorizon / groundColor set the sky gradient and the far ground. groundColor should match the terrain model. ambient: 1 daylight, 0.4 dusk, 0.08 night.

BEATS
- Break the ${settings.duration} seconds into 1–4 beats that cover the whole duration without gaps. Each beat says what happens and how the camera should see it.

ANIMATION LIBRARY (id:name)
${libraryText(library)}`,
    user: `Idea: """${prompt}"""

Director's reading:
- Title: ${interpretation.title}
- Logline: ${interpretation.logline}
- Subjects: ${interpretation.subjects.join(", ")}
- Setting: ${interpretation.setting}
- Mood: ${interpretation.mood}
- Action: ${interpretation.action}

Look: ${settings.style} (${styleHint(settings.style)}). Duration: ${settings.duration} s. Aspect: ${settings.aspect}.`,
  });
}

// ───────────── 3. Creating animations ─────────────

export interface AssetBrief {
  id: string;
  name: string;
  kind: string;
  sizeMeters: number;
  sizeAxis: string;
  rigged: boolean;
  clips: string[];
  note?: string;
}

function assetsText(assets: AssetBrief[]): string {
  return assets
    .map((a) => {
      const motion = a.rigged
        ? `RIGGED humanoid. Clips: ${a.clips.join(", ")}`
        : `NO skeleton (rigid body)${a.note ? ` — ${a.note}` : ""}`;
      return `- ${a.id} ("${a.name}", ${a.kind}, ${a.sizeMeters} m ${a.sizeAxis}): ${motion}`;
    })
    .join("\n");
}

export function animateScene(
  env: Env,
  interpretation: Interpretation,
  beats: ScenePlan["beats"],
  assets: AssetBrief[],
  settings: GenerationSettings,
) {
  return geminiJson<AnimationPlan>(env, {
    label: "animate",
    temperature: 0.6,
    jsonSchema: AnimationJsonSchema,
    parse: AnimationSchema,
    system: `You are the animation director of Kivo. The 3D models below already exist. Place them and choreograph ${settings.duration} seconds of movement.

${WORLD_RULES}

PLACEMENT ("objects")
- Create one object per placement. Use every model at least once. Place the terrain model once at [0, 0, 0] with rotationY 0 and scale 1.
- Models stand on the ground automatically: y = 0 puts their base on the ground. Use y > 0 only for things that fly or float.
- Characters ALWAYS stand on the ground: every character position has y = 0. Never put a character on a roof, balcony, bridge, platform or vehicle — models are solid shapes with no walkable surfaces, so it would float in mid-air. A scene "on a rooftop" is staged on the ground with the skyline around it.
- Never place the hero inside or touching a building: keep at least the building's width between them.
- Repeat set pieces (buildings, trees, rocks) several times with different positions, headings and scales (0.7–1.4) to build the place. Keep them out of the hero's path and leave the area between the hero and likely camera positions clear.
- Give objects short unique ids like "hero", "tower_1", "tree_3".

MOVEMENT ("moves")
- One entry per moving object: keyframes with time t and position. The first keyframe is at t = 0 at the object's start position; add a last keyframe at t = ${settings.duration} if it should hold its end position.
- Natural speeds for a 1.7 m character: walk 1.3 m/s, run 3.5 m/s. Scale speed with the character's height. A walker that covers 6 m needs about 4.5 s.
- For things that walk, drive or fly forward set orientToPath true (they turn to face where they go) and smooth true for curved paths.
- easing describes how the object ARRIVES at that keyframe: "linear" to pass through, "ease_out" to slow to a stop, "ease_in_out" for a gentle move, "hold" to jump there.

SKELETAL CLIPS ("clips")
- Only RIGGED models can use clips, and only the clip names listed for them.
- Cover each rigged character's whole timeline with clips: "walk" or "run" while it travels (loop true), an idle clip while it stands (loop true), one-shot gestures with loop false.
- Match clips to movement: never play "walk" while the position is not changing, and never slide a character without a walk or run clip.

RIGID-BODY LIFE ("procedural")
- Models with NO skeleton cannot bend. Bring them to life with procedural motion layered on top of their path: "hover" for drones and floating things (amplitude 0.05–0.3 m, 0.3–1 Hz), "bob" or "hop" for small creatures moving along the ground (hop amplitude ≈ 15% of their height, 2–3 Hz), "sway" for trees and signs (1–3°, 0.2–0.5 Hz), "wobble" for waddling, "spin" for wheels of light, propellers or planets (frequency = revolutions per second), "shake" for rumble, "pulse" for breathing or glowing things.
- Never use procedural motion on the terrain or on buildings unless the story calls for it.

Everything must happen within 0–${settings.duration} seconds.`,
    user: `Film: ${interpretation.title} — ${interpretation.logline}
Mood: ${interpretation.mood}

Models:
${assetsText(assets)}

Beats:
${beats.map((b) => `- ${b.start}–${b.end}s: ${b.description}`).join("\n") || `- 0–${settings.duration}s: ${interpretation.action}`}`,
  });
}

// ───────────── 4. Cameras, shots and lights ─────────────

/** Compact description of where everything is over time, so cameras can be planned against real motion. */
export function motionSummary(objects: SceneObject[], tracks: Track[], assets: SceneAsset[], duration: number): string {
  const spec = { objects, tracks, cameras: [], lights: [], shots: [] } as unknown as SceneSpec;
  const sampler = new SceneSampler(spec);
  const assetById = new Map(assets.map((a) => [a.id, a]));
  const moving = new Set(tracks.filter((t) => t.type === "transform").map((t) => (t as { objectId: string }).objectId));
  const times = [0, duration * 0.25, duration * 0.5, duration * 0.75, duration].map((t) => Math.round(t * 100) / 100);
  const fmt = (v: number[]) => `[${v.map((n) => Math.round(n * 10) / 10).join(", ")}]`;
  return objects
    .map((o) => {
      const a = assetById.get(o.assetId);
      const size = a ? `${Math.round(a.size.meters * o.scale * 10) / 10} m ${a.size.axis}` : "";
      const facing = (t: number) => `${Math.round(((sampler.sampleObject(o.id, t).rotation[1] % 360) + 360) % 360)}°`;
      const character = a?.kind === "character" || a?.kind === "creature";
      if (!moving.has(o.id)) return `- ${o.id} (${a?.kind ?? "object"}, ${size}): stays at ${fmt(o.position)}${character ? `, facing ${facing(0)}` : ""}`;
      const path = times.map((t) => `${t}s ${fmt(sampler.sampleObject(o.id, t).position)}${character ? ` facing ${facing(t)}` : ""}`).join(" → ");
      return `- ${o.id} (${a?.kind ?? "object"}, ${size}): MOVES ${path}`;
    })
    .join("\n");
}

export function shootScene(
  env: Env,
  interpretation: Interpretation,
  beats: ScenePlan["beats"],
  summary: string,
  settings: GenerationSettings,
) {
  return geminiJson<Cinematography>(env, {
    label: "cinematography",
    temperature: 0.6,
    jsonSchema: CinematographyJsonSchema,
    parse: CinematographySchema,
    system: `You are the cinematographer of Kivo. The scene is already staged and animated. Design the cameras, the edit and the lighting for a ${settings.duration}-second ${settings.aspect} video.

${WORLD_RULES}

CAMERAS
- Use 1–4 cameras. Each camera has keyframes with a position, a target point it looks at, and a vertical fov in degrees (24–35 telephoto/close-up, 40–50 normal, 60–75 wide).
- attachMode "world": position and target are absolute. Good for establishing shots, slow push-ins and static angles.
- attachMode "look_at" with attachObjectId: the camera stays where you put it and keeps aiming at that object. target is an OFFSET from the object's position, NOT a world coordinate — use [0, h, 0] where h is about 60% of the object's height (for a 1 m robot standing anywhere in the world: [0, 0.6, 0]).
- attachMode "follow" with attachObjectId: the camera travels with the object. position and target are BOTH offsets from the object's position. Example chase shot for a 1.2 m robot walking toward +Z: position [1.2, 1.0, -3], target [0, 0.7, 1].
  To orbit an object, use follow with 5 or more keyframes placed around a circle (smooth true, easing "linear").
- Framing distance: to fit a subject of height H with a little headroom at fov F, stand about H × 1.4 / (2 × tan(F/2)) away. For H = 1.7 and F = 40 that is about 3.3 m.
- Keep every camera at least 0.3 m above the ground, outside all models, and with a clear line of sight to its subject. Do not put the camera behind buildings.
- "facing" in the staging is a character's heading (0° faces +Z, 90° faces +X). When a character greets, looks at or reacts to the viewer, put the camera in FRONT of it — along its facing direction — so its face and gesture are seen, not its back.
- Camera keyframe times are in video time (seconds from the start of the video), and a camera only needs keyframes covering the shots that use it.

SHOTS
- Shots are the edit: an ordered list covering 0–${settings.duration} s with no gaps. A ${settings.duration}-second video usually has ${settings.duration <= 6 ? "1–2" : settings.duration <= 20 ? "2–4" : "3–8"} shots.
- transition is how the shot begins: "cut", "fade" (through black) or "dissolve". Use transitionDuration 0 for cuts and 0.3–0.8 for the others. Start the first shot with a short fade if it suits the mood.

LIGHTS
- Always include a key light. Daylight: a "sun" (intensity 2–6) placed high and to one side; its position → target sets the light direction. Night or interiors: "point" / "spot" / "area" lights in watts (300–3000) near the subject, plus a dim cool sun (0.1–0.4) as moonlight.
- Put the key light on the camera's side of the subject (in front of it and off to one side, 30–60° up) so the faces the camera sees are lit. Never put the only strong light behind the subject unless a silhouette is the point.
- Add a fill or rim light when the subject would otherwise be flat or lost against the background.
- Kivo meters exposure automatically, so set light colours and ratios for the mood rather than chasing absolute brightness.
- lightChanges animates intensity/colour over time (for sunsets, flashes, lights switching on). Leave it empty for constant lighting.`,
    user: `Film: ${interpretation.title} — ${interpretation.logline}
Mood: ${interpretation.mood}

Staging (positions are [x, y, z] in metres):
${summary}

Beats:
${beats.map((b) => `- ${b.start}–${b.end}s: ${b.description}`).join("\n") || `- 0–${settings.duration}s: ${interpretation.action}`}`,
  });
}

// ───────────── 5. AI Director edits (Advanced Mode) ─────────────

function compactScene(spec: SceneSpec): string {
  const round = (n: number) => Math.round(n * 100) / 100;
  const v = (a: number[]) => a.map(round);
  return JSON.stringify({
    duration: spec.output.duration,
    world: spec.world,
    assets: spec.assets.map((a) => ({ id: a.id, name: a.name, kind: a.kind, rig: a.rig, size: `${a.size.meters} m ${a.size.axis}` })),
    objects: spec.objects.map((o) => ({ id: o.id, assetId: o.assetId, position: v(o.position), rotationY: round(o.rotation[1]!), scale: o.scale, ...(o.material ? { material: o.material } : {}) })),
    lights: spec.lights.map((l) => ({ id: l.id, type: l.type, color: l.color, intensity: l.intensity, position: v(l.position), target: v(l.target) })),
    cameras: spec.cameras.map((c) => ({
      id: c.id,
      attachMode: c.attach.mode,
      attachObjectId: c.attach.objectId ?? "",
      smooth: c.smooth,
      keyframes: c.keyframes.map((k) => ({ t: k.t, position: v(k.position), target: v(k.target), fov: k.fov, easing: k.easing })),
    })),
    shots: spec.shots.map((s) => ({ cameraId: s.cameraId, start: s.start, end: s.end, transition: s.transition, transitionDuration: s.transitionDuration })),
    moves: spec.tracks
      .filter((t) => t.type === "transform")
      .map((t) => ({
        objectId: t.objectId,
        smooth: t.smooth,
        orientToPath: t.orientToPath,
        keyframes: t.keyframes.map((k) => ({ t: k.t, ...(k.position ? { position: v(k.position) } : {}), ...(k.rotation ? { rotationY: round(k.rotation[1]!) } : {}), ...(k.scale ? { scale: k.scale } : {}), easing: k.easing })),
      })),
    clips: spec.tracks.filter((t) => t.type === "action").map((t) => ({ objectId: t.objectId, clips: t.clips })),
    procedural: spec.tracks.filter((t) => t.type === "procedural").map((t) => ({ objectId: t.objectId, motions: t.motions })),
    lightKeyframes: spec.tracks.filter((t) => t.type === "light").map((t) => ({ lightId: t.lightId, keyframes: t.keyframes })),
  });
}

const COMMON_ACTION = /idle|wave|sit|jump|dance|cheer|talk|look|point|clap|bow|salute|kick|punch|crouch|climb|fall|sleep|pick|push|drink/i;

export function directScene(
  env: Env,
  spec: SceneSpec,
  instruction: string,
  clipsByAsset: Record<string, string[]>,
  limits: Pick<PlanLimits, "maxAssetsPerScene">,
  library: LibraryAction[],
) {
  const rigged = Object.entries(clipsByAsset)
    .map(([id, clips]) => `- ${id}: ${clips.join(", ") || "(no clips)"}`)
    .join("\n");
  const shortLibrary = library
    .filter((a) => COMMON_ACTION.test(a.name))
    .slice(0, 90)
    .map((a) => `${a.action_id}:${a.name}`)
    .join(", ");
  return geminiJson<DirectorResponse>(env, {
    label: "director",
    temperature: 0.4,
    jsonSchema: DirectorJsonSchema,
    parse: DirectorResponseSchema,
    timeoutMs: 75_000,
    system: `You are the AI Director inside Kivo's 3D editor. The user has a finished scene and asks for a change. Answer with the smallest list of operations that makes exactly that change.

${WORLD_RULES}

RULES
- Change only what the user asked for. Everything you do not mention stays exactly as it is.
- Operations replace whole items: "upsert_camera" replaces that camera's keyframes, "set_move" replaces that object's path, "set_clips" replaces that object's clip list, "set_shots" replaces the whole edit (list every shot, covering 0–duration with no gaps). When you replace something, carry over the parts that should not change.
- To change how fast a character walks, change BOTH its path timing (set_move) and the speed of its walk clip (set_clips) so feet do not slide.
- To make something bigger or taller, use update_object with patch.scale (uniform).
- Lighting moods: change the sun's colour/intensity/direction (upsert_light), the sky (set_world), or both. Sunset = low warm sun (#ff9a5c, intensity 2–3) + orange horizon + ambient 0.4.
- Camera vocabulary: attachMode "world" (absolute), "look_at" (stays put, aims at an object; target is an offset), "follow" (travels with an object; position and target are offsets). An orbit is a follow camera with 5+ keyframes around a circle, smooth true, easing "linear". A close-up uses fov 24–35 at a short distance.
- To add a shot, add or reuse a camera and then send set_shots with the full new edit.
- New kinds of objects need a new 3D model: use add_asset (ONE standalone object per prompt; the scene may hold at most ${limits.maxAssetsPerScene} distinct models) followed by add_object to place it. Existing models are never regenerated — to duplicate something that exists, use add_object with its assetId.
- Only rigged characters can use clips, and only clips they have. If the user asks for a body motion no existing clip covers, say so in cannotDo instead of inventing a clip name.
- If the request is unclear or impossible with these operations, leave operations empty and explain in cannotDo.
- summary: one or two plain sentences telling the user what you changed.

Clips available on rigged models:
${rigged || "(no rigged models)"}

Animation library for NEW humanoid models only (id:name): ${shortLibrary}`,
    user: `Current scene:
${compactScene(spec)}

Request: """${instruction}"""`,
  });
}
