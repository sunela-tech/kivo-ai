#!/usr/bin/env node
/**
 * Write apps/api/wrangler.generated.jsonc — a deploy config derived from wrangler.jsonc.
 *
 *   --no-storage   leave out the R2 binding (the account has not enabled R2 yet)
 *   --embed-web    ship the built web app inside the Worker script instead of as Workers
 *                  static assets
 *
 * --embed-web exists for environments where wrangler's asset upload cannot authenticate —
 * for example behind a proxy that injects its own Authorization header, which replaces the
 * upload token that endpoint expects. The normal deploy (static assets) is preferable
 * everywhere else: static requests then never invoke the Worker.
 */
import { createHash } from "node:crypto";
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const api = join(root, "apps", "api");
const dist = join(root, "apps", "web", "dist");
const flags = new Set(process.argv.slice(2));

const source = readFileSync(join(api, "wrangler.jsonc"), "utf8");
const config = JSON.parse(source.replace(/^\s*\/\/.*$/gm, "").replace(/,(\s*[}\]])/g, "$1"));
delete config.$schema;

if (flags.has("--no-storage")) delete config.r2_buckets;

if (flags.has("--embed-web")) {
  const TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
    ".json": "application/json",
    ".woff2": "font/woff2",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".ico": "image/x-icon",
    ".txt": "text/plain; charset=utf-8",
    ".map": "application/json",
  };
  const out = join(api, ".embedded");
  rmSync(out, { recursive: true, force: true });
  mkdirSync(join(out, "files"), { recursive: true });

  const files = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) walk(path);
      else files.push(path);
    }
  };
  walk(dist);
  if (!files.some((f) => f.endsWith("index.html"))) throw new Error("apps/web/dist has no index.html — run `npm run build` first.");

  const imports = [];
  const entries = [];
  files.sort().forEach((path, i) => {
    const url = "/" + relative(dist, path).split("\\").join("/");
    const etag = createHash("sha256").update(readFileSync(path)).digest("hex").slice(0, 20);
    cpSync(path, join(out, "files", `f${i}.bin`));
    imports.push(`import f${i} from "./files/f${i}.bin";`);
    entries.push(`  ${JSON.stringify(url)}: { body: f${i}, type: ${JSON.stringify(TYPES[extname(path)] ?? "application/octet-stream")}, etag: ${JSON.stringify(`"${etag}"`)}, immutable: ${url.startsWith("/assets/")} },`);
  });

  writeFileSync(
    join(out, "entry.ts"),
    `// GENERATED by scripts/make-deploy-config.mjs --embed-web. Do not edit.
// The Kivo Worker with the built web app embedded in the script.
import base from "../src/index";
${imports.join("\n")}

const FILES: Record<string, { body: ArrayBuffer; type: string; etag: string; immutable: boolean }> = {
${entries.join("\n")}
};

function serve(request: Request, url: URL): Response {
  if (request.method !== "GET" && request.method !== "HEAD") return new Response("Method Not Allowed", { status: 405 });
  let file = FILES[url.pathname];
  if (!file) {
    // Client-side routes get the app shell; a missing file with an extension is a real 404.
    if (/\\.[a-z0-9]{2,5}$/i.test(url.pathname)) return new Response("Not found", { status: 404 });
    file = FILES["/index.html"]!;
  }
  const headers = {
    "content-type": file.type,
    etag: file.etag,
    "cache-control": file.immutable ? "public, max-age=31536000, immutable" : "no-cache",
    "x-content-type-options": "nosniff",
    "referrer-policy": "strict-origin-when-cross-origin",
  };
  if (request.headers.get("if-none-match") === file.etag) return new Response(null, { status: 304, headers });
  return new Response(request.method === "HEAD" ? null : file.body, { headers });
}

export default {
  ...base,
  fetch(request: Request, env: Parameters<typeof base.fetch>[1], ctx: ExecutionContext) {
    const url = new URL(request.url);
    if (url.pathname.startsWith("/api/")) return base.fetch(request, env, ctx);
    return serve(request, url);
  },
};
`,
  );
  delete config.assets;
  config.main = ".embedded/entry.ts";
  config.rules = [{ type: "Data", globs: ["**/*.bin"], fallthrough: true }];
  console.log(`Embedded ${files.length} web files (${(files.reduce((n, f) => n + statSync(f).size, 0) / 1024).toFixed(0)} KB) into the Worker.`);
}

writeFileSync(join(api, "wrangler.generated.jsonc"), `// GENERATED by scripts/make-deploy-config.mjs ${[...flags].join(" ")} — do not edit; edit wrangler.jsonc.\n${JSON.stringify(config, null, 2)}\n`);
console.log(`Wrote apps/api/wrangler.generated.jsonc${flags.size ? ` (${[...flags].join(", ")})` : ""}`);
