def _eye(ink: Ink, P, ex, ey, w, h, style, side, lw):
    """side = +1 for the eye on the right of the picture (outer corner at +x)."""
    if style == "happy":
        ink.curve(P([(ex - w, ey + 0.35 * h), (ex - 0.4 * w, ey - 0.35 * h), (ex + 0.4 * w, ey - 0.35 * h),
                     (ex + w, ey + 0.35 * h)]), lw * 2.4)
        return
    inner, outer = ex - side * w, ex + side * w
    if style == "calm":
        ink.curve(P([(inner, ey), (ex - side * 0.4 * w, ey + 0.4 * h), (ex + side * 0.4 * w, ey + 0.42 * h),
                     (outer, ey - 0.05 * h)]), lw * 2.2)
        for k in (0.55, 0.85):
            ink.line(P([(ex + side * k * w, ey + 0.3 * h), (ex + side * (k + 0.16) * w, ey + 0.62 * h)]), lw * 0.8)
        return
    if style == "surprised":
        ink.shape(P(ell(ex, ey, 0.78 * w, 1.05 * h)), 255, 0, lw * 1.3)
        ink.shape(P(ell(ex, ey, 0.24 * w, 0.3 * h)), 0, 0, 0)
        ink.shape(P(ell(ex - 0.08 * w, ey - 0.1 * h, 0.08 * w, 0.1 * h)), 255, 0, 0)
        return
    ix, iy, rx, ry = ex, ey + 0.08 * h, 0.56 * w, 0.98 * h
    iris = ell(ix, iy, rx, ry)
    ink.shape(P(iris), 255, 0.45, lw * 0.9)
    ink.fill(P([p for p in iris if p[1] <= iy - 0.15 * ry]), 0)                     # shadow under the lid
    ink.shape(P(ell(ix, iy + 0.08 * ry, 0.4 * rx, 0.46 * ry)), 0, 0, 0)              # pupil
    ink.shape(P(ell(ix - 0.32 * rx, iy - 0.42 * ry, 0.3 * rx, 0.26 * ry)), 255, 0, 0)  # highlights
    ink.shape(P(ell(ix + 0.34 * rx, iy + 0.5 * ry, 0.15 * rx, 0.13 * ry)), 255, 0, 0)
    lid = -1.0 if style != "half" else -0.45
    ink.curve(P([(inner, ey - 0.12 * h), (ex - side * 0.45 * w, ey + (lid + 0.05) * h),
                 (ex + side * 0.45 * w, ey + lid * h), (outer, ey - 0.38 * h),
                 (outer + side * 0.14 * w, ey - 0.08 * h)]), lw * 3.2, taper=0.3)
    if style == "half":
        ink.fill(P([(inner, ey - 0.5 * h), (outer, ey - 0.8 * h), (outer, ey - 1.5 * h), (inner, ey - 1.5 * h)]), 255)
        ink.curve(P([(inner, ey - 0.3 * h), (ex, ey - 0.55 * h), (outer, ey - 0.5 * h)]), lw * 2.6, taper=0.3)
    ink.curve(P([(ex - 0.55 * w, ey + 1.04 * h), (ex, ey + 1.12 * h), (ex + 0.55 * w, ey + 1.04 * h)]), lw * 0.8)
    ink.curve(P([(inner + side * 0.2 * w, ey - 1.3 * h), (ex, ey - 1.42 * h), (outer, ey - 0.95 * h)]), lw * 0.6)


def _bangs_edge(rng, kind: str, n: int) -> list:
    """Lower edge of the fringe, from the right temple to the left one."""
    xs = np.linspace(1.02, -1.02, 2 * n + 1)
    lean = float(rng.uniform(0.08, 0.2)) * pick(rng, (-1, 1))
    pts = []
    for i, x in enumerate(xs):
        side = abs(x)
        if i % 2 == 0:                                   # notch
            y = -0.72 + rng.uniform(-0.08, 0.1)
            if kind == "straight":
                y = -0.36
            if kind == "parted" and abs(x) < 0.12:
                y = -1.12
        else:                                            # tip
            y = rng.uniform(-0.34, -0.08) + 0.3 * side * side
            if kind == "straight":
                y = -0.27 + 0.25 * side ** 3
            if kind == "parted":
                y = -0.5 + 0.5 * side
            if kind == "swept":
                x = x + lean
                y = -0.3 + 1.2 * lean * x
        pts.append((float(x), float(y)))
    pts[0] = (1.08, -0.12)
    pts[-1] = (-1.08, -0.12)
    return pts


def draw_character(ink: Ink, rng, a: dict, cx: float, cy: float, sc: float, tilt: float = 0.0,
                   expr: str | None = None, body: bool = True):
    """Draw a bust. (cx, cy) is the face centre in pixels, sc pixels per head unit."""
    expr = expr or a["expr"]
    shape_rng = np.random.default_rng(a["seed"])     # identity: same hair shape in every panel
    c, s = math.cos(tilt), math.sin(tilt)

    def P(pts):                                      # head space (tilted)
        q = np.asarray(pts, dtype=float)
        return np.stack([cx + sc * (q[:, 0] * c - q[:, 1] * s), cy + sc * (q[:, 0] * s + q[:, 1] * c)], axis=1)

    def B(pts):                                      # body space (upright)
        q = np.asarray(pts, dtype=float)
        return np.stack([cx + sc * q[:, 0], cy + sc * q[:, 1]], axis=1)

    lw = max(1.6, sc * 0.022)
    hfill, htone = HAIR[a["color"]]
    hair, gender = a["hair"], a["gender"]

    # 1. hair behind the head
    cap = [(0, -1.42), (0.72, -1.3), (1.16, -0.75), (1.2, -0.05), (1.05, 0.42)]
    back = {"bob": [(0, -1.42), (0.75, -1.3), (1.2, -0.7), (1.3, 0.2), (1.22, 0.85), (0.85, 1.12), (0.5, 0.95)],
            "long": [(0, -1.42), (0.78, -1.3), (1.22, -0.7), (1.36, 0.4), (1.5, 1.6), (1.42, 2.7), (0.9, 2.95), (0.4, 2.6)],
            }.get(hair, cap)
    if hair == "spiky":
        pts = []
        for i, ang in enumerate(np.linspace(200, -20, 15)):
            r = 1.24 if i % 2 == 0 else float(shape_rng.uniform(1.5, 1.78))
            pts.append((r * math.cos(math.radians(ang)) * 0.95, -0.25 - r * math.sin(math.radians(ang)) * 0.95))
        ink.shape(P([(-1.08, 0.35)] + pts + [(1.08, 0.35)]), hfill, htone, lw)
    else:
        ink.shape(P(sym(back)), hfill, htone, lw, smooth=True)
    if hair == "twin tails":
        tail = [(1.0, -0.75), (1.45, -0.7), (1.85, 0.0), (1.95, 1.2), (1.7, 2.2), (1.45, 2.45), (1.4, 1.5), (1.3, 0.4), (1.12, -0.2)]
        for sgn in (1, -1):
            ink.shape(P([(sgn * x, y) for x, y in tail]), hfill, htone, lw, smooth=True)
    elif hair == "ponytail":
        sgn = 1 if a["seed"] % 2 else -1
        tail = [(0.5, -1.35), (1.3, -1.5), (1.95, -0.9), (2.05, 0.3), (1.8, 1.3), (1.55, 1.5), (1.6, 0.4), (1.4, -0.5), (0.9, -0.95)]
        ink.shape(P([(sgn * x, y) for x, y in tail]), hfill, htone, lw, smooth=True)
    elif hair == "buns":
        for sgn in (1, -1):
            ink.shape(P(ell(sgn * 0.95, -1.22, 0.38, 0.36)), hfill, htone, lw)
    if "cat ears" in a["acc"]:
        for sgn in (1, -1):
            ink.shape(P([(sgn * 0.3, -1.3), (sgn * 0.9, -2.0), (sgn * 1.12, -0.95)]), hfill, htone, lw)
            ink.shape(P([(sgn * 0.52, -1.3), (sgn * 0.86, -1.72), (sgn * 0.98, -1.12)]), 255, 0.35, lw * 0.6)

    # 2. body and outfit
    ofill = {"white": (255, 0.0), "tone": (255, 0.32), "black": (0, 0.0)}[a["outfit_fill"]]
    outfit = a["outfit"] if body else "none"
    if outfit == "school jacket":
        ofill = (0, 0.0)
    if outfit == "sailor uniform":
        ofill = (255, 0.0)
    if body:
        torso = [(0.34, 1.36), (0.95, 1.56), (1.62, 1.82), (1.96, 2.5), (2.05, 3.8)]
        ink.shape(B(torso + [(-x, y) for x, y in reversed(torso)]), ofill[0], ofill[1], lw)
        ink.fill(B([(-0.3, 0.7), (0.3, 0.7), (0.36, 1.52), (-0.36, 1.52)]), 255)              # neck
        ink.line(B([(-0.3, 0.85), (-0.35, 1.45)]), lw)
        ink.line(B([(0.3, 0.85), (0.35, 1.45)]), lw)
    line_c = 255 if ofill[0] == 0 else 0
    if outfit == "t-shirt":
        ink.fill(B([(-0.36, 1.34), (0.36, 1.34), (0.3, 1.6), (0, 1.72), (-0.3, 1.6)]), 255)
        ink.curve(B([(-0.44, 1.38), (-0.25, 1.62), (0, 1.72), (0.25, 1.62), (0.44, 1.38)]), lw * 1.2, color=0, taper=None)
    elif outfit == "sailor uniform":
        dark = a["outfit_fill"] != "white"
        ink.fill(B([(-0.36, 1.34), (0.36, 1.34), (0, 2.2)]), 255)
        collar = [(-0.36, 1.36), (-1.2, 1.62), (-1.0, 2.25), (0, 2.95), (1.0, 2.25), (1.2, 1.62), (0.36, 1.36), (0, 2.25)]
        ink.shape(B(collar), 0 if dark else 255, 0, lw)
        ink.line(B([(-1.04, 1.74), (-0.9, 2.2), (0, 2.76), (0.9, 2.2), (1.04, 1.74)]), lw * 0.9, 255 if dark else 0)
        ink.shape(B([(0, 2.82), (-0.42, 2.62), (-0.36, 3.12)]), 0 if not dark else 255, 0, lw)
        ink.shape(B([(0, 2.82), (0.42, 2.62), (0.36, 3.12)]), 0 if not dark else 255, 0, lw)
    elif outfit == "shirt and tie":
        ink.fill(B([(-0.36, 1.34), (0.36, 1.34), (0.5, 3.8), (-0.5, 3.8)]), 255)
        ink.shape(B([(-0.1, 1.62), (0.1, 1.62), (0.16, 1.84), (0.27, 2.95), (0, 3.25), (-0.27, 2.95), (-0.16, 1.84)]), 0, 0, lw)
        for sgn in (1, -1):
            ink.shape(B([(sgn * 0.36, 1.36), (sgn * 0.78, 1.6), (sgn * 0.3, 1.98), (0, 1.62)]), 255, 0, lw)
            ink.line(B([(sgn * 0.5, 1.9), (sgn * 0.5, 3.8)]), lw, 0)
    elif outfit == "hoodie":
        for sgn in (1, -1):
            ink.shape(B([(sgn * 0.3, 1.25), (sgn * 0.95, 1.5), (sgn * 0.78, 2.05), (sgn * 0.08, 2.25), (sgn * 0.02, 1.7)]),
                      ofill[0], ofill[1], lw, smooth=True)
            ink.line(B([(sgn * 0.18, 2.15), (sgn * 0.22, 2.9)]), lw, line_c)
            ink.shape(B(ell(sgn * 0.22, 2.95, 0.05, 0.05, 10)), line_c, 0, 0)
        ink.curve(B([(-0.9, 3.4), (0, 3.2), (0.9, 3.4)]), lw, color=line_c, taper=None)
    elif outfit == "kimono":
        ink.fill(B([(-0.36, 1.34), (0.36, 1.34), (0, 2.3)]), 255)
        ink.shape(B([(0.34, 1.36), (0.66, 1.5), (-0.5, 3.8), (-0.95, 3.8)]), 255, 0, lw)
        ink.shape(B([(-0.34, 1.36), (-0.66, 1.5), (0.12, 2.5), (0.36, 2.22)]), 255, 0, lw)
    elif outfit == "school jacket":
        ink.shape(B([(-0.4, 1.26), (0.4, 1.26), (0.44, 1.56), (-0.44, 1.56)]), 0, 0, 0)
        ink.line(B([(-0.4, 1.3), (0.4, 1.3)]), lw * 0.7, 255)
        ink.line(B([(0, 1.56), (0, 3.8)]), lw * 0.8, 255)
        for k in range(4):
            ink.shape(B(ell(0.12, 1.95 + 0.48 * k, 0.07, 0.07, 10)), 255, 0, 0)

    # 3. head
    for sgn in (1, -1):
        ink.shape(P([(sgn * 0.98, -0.12), (sgn * 1.15, -0.16), (sgn * 1.18, 0.1), (sgn * 1.06, 0.34), (sgn * 0.95, 0.3)]),
                  255, 0, lw, smooth=True)
    jaw, chin = a["jaw"], a["chin"]
    head = [(0, -1.22), (0.62, -1.08), (0.98, -0.55), (1.0, 0.0), (0.9, 0.42), (jaw, 0.78), (0.22, chin - 0.03), (0, chin)]
    ink.shape(P(sym(head)), 255, 0, lw * 1.15, smooth=True)

    # 4. face
    w = 0.33
    h = {"normal": 0.27, "big": 0.35, "narrow": 0.18}[a["eyes"]]
    ex, ey = 0.46, 0.1
    styles = {"smiling": ("open", "open"), "neutral": ("open", "open"), "laughing": ("happy", "happy"),
              "surprised": ("surprised", "surprised"), "angry": ("half", "half"), "sad": ("open", "open"),
              "calm": ("calm", "calm"), "winking": ("open", "happy")}[expr]
    for sgn, st in zip((-1, 1), styles):
        _eye(ink, P, sgn * ex, ey, w, h, st, sgn, lw)
    by = ey - h - 0.26
    di, do = {"angry": (0.14, -0.08), "sad": (-0.1, 0.08), "surprised": (-0.12, -0.1)}.get(expr, (0.0, 0.02))
    for sgn in (-1, 1):
        ink.curve(P([(sgn * 0.2, by + di), (sgn * 0.46, by - 0.05 + (di + do) / 2), (sgn * 0.74, by + do)]), lw * 1.5)
    ink.line(P([(0.02, 0.4), (0.07, 0.5), (0.0, 0.51)]), lw * 0.7)
    if expr in ("smiling", "winking"):
        ink.curve(P([(-0.2, 0.7), (0, 0.79), (0.2, 0.7)]), lw * 1.3)
    elif expr == "laughing":
        ink.shape(P([(-0.24, 0.66), (0.24, 0.66), (0.2, 0.82), (0, 0.93), (-0.2, 0.82)]), 255, 0, lw, smooth=True)
        ink.line(P([(-0.24, 0.67), (0.24, 0.67)]), lw)
    elif expr == "surprised":
        ink.shape(P(ell(0, 0.77, 0.07, 0.1, 14)), 255, 0, lw)
    elif expr in ("angry", "sad"):
        ink.curve(P([(-0.17, 0.8), (0, 0.72), (0.17, 0.8)]), lw * 1.3)
    else:
        ink.line(P([(-0.11, 0.75), (0.11, 0.75)]), lw * 1.1)
    if a["blush"]:
        for sgn in (-1, 1):
            for k in range(3):
                x = sgn * (0.56 + 0.08 * k)
                ink.line(P([(x + 0.04, 0.4), (x - 0.04, 0.54)]), lw * 0.6)

    # 5. hair in front
    n = int(shape_rng.integers(4, 8))
    arc = [(-1.1, -0.12), (-1.14, -0.65), (-0.82, -1.22), (0, -1.42), (0.82, -1.22), (1.14, -0.65), (1.1, -0.12)]
    from ..vector.render import catmull_rom
    upper = [tuple(p) for p in catmull_rom(arc)]
    fringe = upper + _bangs_edge(shape_rng, a["bangs"], n)
    ink.shape(P(fringe), hfill, htone, lw)
    if hair in ("long", "bob", "twin tails", "ponytail"):
        for sgn in (1, -1):
            ink.shape(P([(sgn * 1.1, -0.3), (sgn * 1.17, 0.5), (sgn * 1.02, 1.18), (sgn * 0.9, 0.6), (sgn * 0.86, -0.2)]),
                      hfill, htone, lw)
    if hfill == 0:
        ink.curve(P([(-0.72, -0.9), (-0.3, -1.06), (0.3, -1.06), (0.72, -0.9)]), lw * 2.4, color=255, taper=0.15)
        for x in (-0.38, 0.05, 0.42):
            ink.line(P([(x, -1.2), (x + 0.05, -0.85)]), lw * 0.9, 0)
    else:
        for x in np.linspace(-0.7, 0.7, 5):
            ink.curve(P([(x * 0.3, -1.36), (x * 0.8, -1.0), (x * 1.05, -0.55)]), lw * 0.6)

    # 6. accessories
    if "glasses" in a["acc"]:
        for sgn in (-1, 1):
            ink.line(P(ell(sgn * ex, ey + 0.02, 0.4, 0.34, 24)), lw * 1.2, 0, closed=True)
            ink.line(P([(sgn * 0.86, ey), (sgn * 1.08, ey - 0.08)]), lw * 1.1)
        ink.line(P([(-0.07, ey), (0.07, ey)]), lw * 1.1)
    if "hair ribbon" in a["acc"]:
        bx, by2 = 0.78, -1.12
        col = 255 if hfill == 0 else 0
        for sgn in (-1, 1):
            ink.shape(P([(bx, by2), (bx + sgn * 0.42, by2 - 0.26), (bx + sgn * 0.42, by2 + 0.26)]), col, 0, lw)
        ink.shape(P(ell(bx, by2, 0.09, 0.09, 12)), col, 0, lw)
    if "headband" in a["acc"]:
        col = 255 if hfill == 0 else 0
        ink.curve(P([(-1.05, -0.62), (-0.6, -1.12), (0, -1.26), (0.6, -1.12), (1.05, -0.62)]), lw * 3.2, color=col, taper=None)


def draw_chibi(ink: Ink, rng, a: dict, cx: float, cy: float, sc: float):
    """Full-body super-deformed figure: big head on a small body. cy is the head centre."""
    lw = max(1.6, sc * 0.022)
    ofill = {"white": (255, 0.0), "tone": (255, 0.32), "black": (0, 0.0)}[a["outfit_fill"]]

    def B(pts):
        q = np.asarray(pts, dtype=float)
        return np.stack([cx + sc * q[:, 0], cy + sc * q[:, 1]], axis=1)

    pose = pick(rng, ("standing", "waving", "jumping", "cheering"))
    arms = {"standing": ((0.95, 2.0), (0.95, 2.0)), "waving": ((0.95, 2.0), (1.45, 0.85)),
            "jumping": ((1.4, 1.1), (1.4, 1.1)), "cheering": ((1.1, 0.6), (1.1, 0.6))}[pose]
    legs = [(0.3, 3.05), (0.3, 3.05)] if pose != "jumping" else [(0.55, 2.8), (0.45, 2.95)]
    for sgn, (lx, ly) in zip((-1, 1), legs):
        ink.shape(B([(sgn * 0.08, 2.2), (sgn * 0.5, 2.2), (sgn * (lx + 0.22), ly), (sgn * (lx - 0.16), ly)]), 255, 0, lw)
        ink.shape(B(ell(sgn * (lx + 0.06), ly + 0.06, 0.26, 0.13, 14)), 0, 0, lw)
    for sgn, (axx, ay) in zip((-1, 1), arms):
        ink.shape(B([(sgn * 0.42, 1.28), (sgn * 0.6, 1.2), (sgn * (axx + 0.1), ay), (sgn * (axx - 0.12), ay + 0.12)]),
                  ofill[0], ofill[1], lw)
        ink.shape(B(ell(sgn * axx, ay + 0.05, 0.14, 0.14, 12)), 255, 0, lw)
    ink.shape(B([(-0.45, 1.2), (0.45, 1.2), (0.62, 2.3), (-0.62, 2.3)]), ofill[0], ofill[1], lw)
