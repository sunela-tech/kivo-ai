"""Procedural manga characters for the INKOS 1 Pro training set.

A character is a bag of attributes (hair, eyes, expression, outfit,
accessories) that is both drawn and written into the caption, so the model
sees which words go with which marks. All artwork is generated by this code;
nothing is traced or copied from existing manga.

Head coordinates: origin at the centre of the face, 1 unit = half the head
width, y down. The chin is near y = 1.05, shoulders near y = 1.7.
"""
from __future__ import annotations

import math

import numpy as np

from .manga_draw import Ink


def pick(rng, seq):
    return seq[int(rng.integers(len(seq)))]


def sym(right):
    """Mirror a right-hand outline (top to bottom) into a closed symmetric loop."""
    return list(right) + [(-x, y) for x, y in reversed(right) if abs(x) > 1e-9]


def ell(cx, cy, rx, ry, n=26):
    a = np.linspace(0, 2 * math.pi, n, endpoint=False)
    return list(zip(cx + rx * np.cos(a), cy + ry * np.sin(a)))


HAIR = {"black": (0, 0.0), "white": (255, 0.0), "gray": (255, 0.42)}
EXPRESSIONS = ("smiling", "smiling", "neutral", "laughing", "surprised", "angry", "sad", "calm", "winking")
GIRL_HAIR = ("long", "long", "bob", "twin tails", "ponytail", "short", "buns")
BOY_HAIR = ("short", "spiky", "spiky", "bob")
BANGS = ("spiky", "straight", "parted", "swept")
GIRL_OUTFITS = ("sailor uniform", "shirt and tie", "hoodie", "t-shirt", "kimono")
BOY_OUTFITS = ("school jacket", "shirt and tie", "hoodie", "t-shirt", "kimono")


def sample_character(rng) -> dict:
    g = pick(rng, ("girl", "girl", "boy"))
    acc = []
    if rng.random() < 0.2:
        acc.append("glasses")
    if g == "girl" and rng.random() < 0.25:
        acc.append("hair ribbon")
    if rng.random() < 0.1:
        acc.append("cat ears")
    elif rng.random() < 0.1:
        acc.append("headband")
    return {
        "gender": g,
        "hair": pick(rng, GIRL_HAIR if g == "girl" else BOY_HAIR),
        "color": pick(rng, ("black", "black", "white", "gray")),
        "bangs": pick(rng, BANGS),
        "eyes": pick(rng, ("normal", "normal", "big", "narrow")),
        "expr": pick(rng, EXPRESSIONS),
        "outfit": pick(rng, GIRL_OUTFITS if g == "girl" else BOY_OUTFITS),
        "outfit_fill": pick(rng, ("white", "white", "tone", "black")),
        "acc": acc,
        "blush": rng.random() < 0.3,
        "jaw": float(rng.uniform(0.56, 0.72)),
        "chin": float(rng.uniform(1.0, 1.12)),
        "seed": int(rng.integers(1 << 30)),
    }


def character_tags(a: dict, with_outfit: bool = True) -> list[str]:
    tags = [a["gender"], f"{a['hair']} {a['color']} hair", f"{a['bangs']} bangs"]
    if a["eyes"] != "normal":
        tags.append(f"{a['eyes']} eyes")
    tags.append(a["expr"])
    if with_outfit:
        tags.append(a["outfit"])
    tags += a["acc"]
    if a["blush"]:
        tags.append("blush")
    return tags


def short_description(a: dict) -> str:
    return f"{a['gender']} with {a['hair']} {a['color']} hair"


